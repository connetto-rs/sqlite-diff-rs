/// `i32` to `u32` for an exponent or index the algorithm keeps non-negative.
#[expect(
    clippy::cast_sign_loss,
    reason = "callers pass values the algorithm keeps non-negative"
)]
fn unsigned(v: i32) -> u32 {
    debug_assert!(v >= 0, "negative exponent or index {v}");
    v as u32
}

/// `u32` to `i32` for an exponent or index the algorithm keeps below `2^31`.
#[expect(
    clippy::cast_possible_wrap,
    reason = "callers pass values the algorithm keeps below 2^31"
)]
fn signed(v: u32) -> i32 {
    debug_assert!(i32::try_from(v).is_ok(), "exponent or index {v} above i32");
    v as i32
}

/// `e == 0 ? 1 : ceil(log2(5^e))`.
fn pow5bits(e: u32) -> i32 {
    signed(((e * 1217359) >> 19) + 1)
}

/// `floor(log10(2^e))`.
const fn log10_pow2(e: u32) -> u32 {
    (e * 78913) >> 18
}

/// `floor(log10(5^e))`.
const fn log10_pow5(e: u32) -> u32 {
    (e * 732923) >> 20
}

/// Whether `value` is divisible by `5^p`.
fn multiple_of_power_of_5(mut value: u32, p: u32) -> bool {
    let mut count = 0;
    while value % 5 == 0 {
        value /= 5;
        count += 1;
    }
    count >= p
}

/// Whether `value` is divisible by `2^p`.
const fn multiple_of_power_of_2(value: u32, p: u32) -> bool {
    value & ((1 << p) - 1) == 0
}

/// `(m * factor) >> shift`, for a `shift` above 32 that leaves 32 bits.
#[expect(
    clippy::cast_possible_truncation,
    reason = "Ryu's choice of shift leaves a result below 2^32, which the debug assertion checks"
)]
fn mul_shift(m: u32, factor: u64, shift: i32) -> u32 {
    debug_assert!(shift > 32, "shift {shift} not above 32");
    let bits0 = u64::from(m) * (factor & 0xffff_ffff);
    let bits1 = u64::from(m) * (factor >> 32);
    let shifted = ((bits0 >> 32) + bits1) >> (shift - 32);
    debug_assert!(u32::try_from(shifted).is_ok(), "{shifted} above u32");
    shifted as u32
}

fn mul_pow5_inv_div_pow2(m: u32, q: u32, j: i32) -> u32 {
    // q is below 31, the table's length, so the index cast is lossless.
    mul_shift(m, POW5_INV_SPLIT[q as usize], j)
}

fn mul_pow5_div_pow2(m: u32, i: u32, j: i32) -> u32 {
    // i is below 47, the table's length, so the index cast is lossless.
    mul_shift(m, POW5_SPLIT[i as usize], j)
}

/// The decimal `mantissa × 10^exponent` PostgreSQL's `float4out` prints for
/// the magnitude of `f`, or `None` for zero, an infinity or NaN, which it
/// prints as words or `0`.
pub(crate) fn float4out_digits(f: f32) -> Option<(u32, i32)> {
    let bits = f.to_bits();
    let ieee_mantissa = bits & ((1 << MANTISSA_BITS) - 1);
    let ieee_exponent = (bits >> MANTISSA_BITS) & ((1 << EXPONENT_BITS) - 1);
    if ieee_exponent == (1 << EXPONENT_BITS) - 1 || (ieee_exponent == 0 && ieee_mantissa == 0) {
        return None;
    }
    Some(
        small_int(ieee_mantissa, ieee_exponent)
            .unwrap_or_else(|| f2d(ieee_mantissa, ieee_exponent)),
    )
}

/// PostgreSQL's `f2d_small_int`, which prints an integer in `[1, 2^24)` whole.
fn small_int(ieee_mantissa: u32, ieee_exponent: u32) -> Option<(u32, i32)> {
    let e2 = signed(ieee_exponent) - BIAS - signed(MANTISSA_BITS);
    if !(-signed(MANTISSA_BITS)..=0).contains(&e2) {
        return None;
    }
    let shift = unsigned(-e2);
    if ieee_mantissa & ((1 << shift) - 1) != 0 {
        return None;
    }
    Some((((1 << MANTISSA_BITS) | ieee_mantissa) >> shift, 0))
}

/// `f2d` with `acceptBounds` false.
fn f2d(ieee_mantissa: u32, ieee_exponent: u32) -> (u32, i32) {
    // Two extra bits so the bounds computation stays in integers.
    let (e2, m2) = if ieee_exponent == 0 {
        (1 - BIAS - signed(MANTISSA_BITS) - 2, ieee_mantissa)
    } else {
        (
            signed(ieee_exponent) - BIAS - signed(MANTISSA_BITS) - 2,
            (1 << MANTISSA_BITS) | ieee_mantissa,
        )
    };

    let mv = 4 * m2;
    let mp = 4 * m2 + 2;
    let mm_shift = u32::from(ieee_mantissa != 0 || ieee_exponent <= 1);
    let mm = 4 * m2 - 1 - mm_shift;

    let (mut vr, mut vp, mut vm);
    let e10;
    let mut vr_is_trailing_zeros = false;
    let mut last_removed_digit = 0;
    if e2 >= 0 {
        let q = log10_pow2(unsigned(e2));
        e10 = signed(q);
        let k = POW5_INV_BITCOUNT + pow5bits(q) - 1;
        let i = -e2 + signed(q) + k;
        vr = mul_pow5_inv_div_pow2(mv, q, i);
        vp = mul_pow5_inv_div_pow2(mp, q, i);
        vm = mul_pow5_inv_div_pow2(mm, q, i);
        if q != 0 && (vp - 1) / 10 <= vm / 10 {
            let l = POW5_INV_BITCOUNT + pow5bits(q - 1) - 1;
            last_removed_digit = mul_pow5_inv_div_pow2(mv, q - 1, -e2 + signed(q) - 1 + l) % 10;
        }
        if q <= 9 {
            // Only one of mp, mv and mm can be a multiple of 5, if any.
            if mv % 5 == 0 {
                vr_is_trailing_zeros = multiple_of_power_of_5(mv, q);
            } else {
                vp -= u32::from(multiple_of_power_of_5(mp, q));
            }
        }
    } else {
        let q = log10_pow5(unsigned(-e2));
        e10 = signed(q) + e2;
        let i = unsigned(-e2) - q;
        let k = pow5bits(i) - POW5_BITCOUNT;
        let j = signed(q) - k;
        vr = mul_pow5_div_pow2(mv, i, j);
        vp = mul_pow5_div_pow2(mp, i, j);
        vm = mul_pow5_div_pow2(mm, i, j);
        if q != 0 && (vp - 1) / 10 <= vm / 10 {
            let j = signed(q) - 1 - (pow5bits(i + 1) - POW5_BITCOUNT);
            last_removed_digit = mul_pow5_div_pow2(mv, i + 1, j) % 10;
        }
        if q <= 1 {
            // mv = 4 * m2 has at least two trailing 0 bits, and mp = mv + 2 one.
            vr_is_trailing_zeros = true;
            vp -= 1;
        } else if q < 31 {
            vr_is_trailing_zeros = multiple_of_power_of_2(mv, q - 1);
        }
    }

    let mut removed = 0;
    while vp / 10 > vm / 10 {
        vr_is_trailing_zeros &= last_removed_digit == 0;
        last_removed_digit = vr % 10;
        vr /= 10;
        vp /= 10;
        vm /= 10;
        removed += 1;
    }
    if vr_is_trailing_zeros && last_removed_digit == 5 && vr % 2 == 0 {
        // Round to even when the exact value is ...50..0.
        last_removed_digit = 4;
    }
    // vr + 1 when vr is outside the bounds or rounds up.
    let output = vr + u32::from(vr == vm || last_removed_digit >= 5);
    (output, e10 + removed)
}
